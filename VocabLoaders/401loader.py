    """
    Bu fonksiyon, veritabanındaki wordLevel'ı '401' olan tüm kelimeleri siler.
    DİKKAT: Bu işlem geri alınamaz!
    """
    
    print("401 seviyesindeki kelimeler siliniyor...")
    
    # wordLevel'ı '501' olan kelimeleri filtrele
    words_to_delete = Word.objects.filter(wordLevel='401').filter(isBaseWord = True)
    
    # Filtrelenen kelimelerin sayısını al (silme işleminden önce)
    count = words_to_delete.count()
    
    if count > 0:
        # Silme işlemini gerçekleştir
        # delete() metodu bir tuple döner: (silinen toplam obje sayısı, silinen obje türüne göre detaylar içeren bir sözlük)
        deleted_info = words_to_delete.delete()
